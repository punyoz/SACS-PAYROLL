$function$;

-- Columns never exported, whatever the table.
CREATE OR REPLACE FUNCTION public.backup_export_hidden_columns()
 RETURNS text[]
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  SELECT ARRAY[
    'sss_number_enc', 'philhealth_number_enc', 'pagibig_number_enc', 'tin_number_enc', 'prc_license_no_enc',
    'code_hash', 'data_url', 'proof_url'
  ]::text[];

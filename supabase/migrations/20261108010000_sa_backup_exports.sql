-- Super Admin backup exports (2026-11-08).
--
-- The Super Admin downloads payroll records and a full data backup from
-- Backup & Recovery, for every branch, read-only. The app reaches the
-- database with the service role (RLS bypassed), so the rule is enforced in
-- the only way in, as the announcement functions do: SECURITY DEFINER
-- functions that check the acting user, executable by the service role only.
--
--   backup_actor_is_super_admin(actor)   an active (not archived) Super Admin
--   backup_export_tables()               the tables the backup may read
--   backup_export_count(actor, table)    exact row count of one table
--   backup_export_counts(actor, tables?) every table's row count, one call
--   backup_export_page(actor, table, after, limit)
--                                        one page of a table, in primary-key
--                                        order (keyset paging), as JSON rows,
--                                        with secrets and file blobs removed
--   backup_payroll_export(actor, after, limit)
--                                        one page of payroll_entries with
--                                        the branch name, exactly as stored
--
-- Never readable through these functions:
--   auth_email_otps   sign-in code hashes (security secrets)
--   auth_throttle     sign-in throttling counters (short-lived)
--   notifications     bell messages (regenerated by the app, not records)
-- and these columns of the tables that are: the encrypted government ID
-- columns (*_enc; the app exports the decrypted numbers instead), code_hash,
-- employee_license_documents.data_url and leave_requests.proof_url (whole
-- files as text; far beyond an Excel cell). Passwords and tokens live in the
-- auth schema, which none of this reads.
--
-- Functions only: no table or row is changed. Safe to run more than once.

CREATE OR REPLACE FUNCTION public.backup_actor_is_super_admin(p_actor uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = p_actor
      AND lower(COALESCE(p.role::TEXT, '')) = 'super_admin'
      AND COALESCE(p.archived, FALSE) = FALSE
  );
$function$;

